/**
 * Regenerates src/data/events/index.ts from every *.ts file in src/data/events
 * that exports an `*_EVENTS` array. Run after adding content files:
 *   node scripts/register-events.mjs
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const dir = path.resolve('src/data/events');
const files = readdirSync(dir)
  .filter((f) => f.endsWith('.ts') && f !== 'index.ts')
  .sort();
const entries = [];
for (const f of files) {
  const src = readFileSync(path.join(dir, f), 'utf8');
  const names = [...src.matchAll(/export const ([A-Z0-9_]+_EVENTS)\s*:/g)].map((m) => m[1]);
  for (const n of names) entries.push({ file: f.replace(/\.ts$/, ''), name: n });
}
const imports = entries.map((e) => `import { ${e.name} } from './${e.file}';`).join('\n');
const spread = entries.map((e) => `...${e.name}`).join(', ');
const out = `import type { EventDef } from '@/engine/events/schema';
${imports}

/** All random events. Generated by scripts/register-events.mjs — add a file, then re-run it. */
export const EVENTS: readonly EventDef[] = [${spread}];
`;
writeFileSync(path.join(dir, 'index.ts'), out);
console.log(`registered ${entries.length} event file(s): ${entries.map((e) => e.file).join(', ')}`);
